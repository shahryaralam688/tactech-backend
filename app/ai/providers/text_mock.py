"""Local mock text provider for tests / no-key auto mode."""

from __future__ import annotations

import json
from typing import Any, AsyncIterator

from app.ai.providers.base import TextLLMProvider


class MockTextProvider(TextLLMProvider):
    name = "mock"

    async def complete(
        self,
        messages: list[dict[str, Any]],
        *,
        temperature: float,
        max_tokens: int,
        response_json: bool = False,
    ) -> str:
        if response_json:
            # Caller may inject catalog ids via system message; return a minimal valid shell.
            # Program generate service validates/retries — mock returns empty days so service
            # builds a deterministic fallback when mock is detected, OR we parse a hint.
            last = ""
            for msg in reversed(messages):
                if msg.get("role") == "user":
                    last = str(msg.get("content") or "")
                    break
            # Prefer exercise ids listed after "VALID_EXERCISE_IDS:" in any message
            ids: list[str] = []
            for msg in messages:
                text = str(msg.get("content") or "")
                marker = "VALID_EXERCISE_IDS:"
                if marker in text:
                    raw = text.split(marker, 1)[1].strip().split("\n")[0]
                    ids = [x.strip() for x in raw.split(",") if x.strip()]
                    break
            if not ids:
                ids = ["ex-bodyweight-squat"]
            day_count = 3
            weekdays = ["Mon", "Wed", "Fri", "Tue", "Thu", "Sat", "Sun"]
            days = []
            for i in range(day_count):
                eid = ids[i % len(ids)]
                days.append(
                    {
                        "weekday": weekdays[i],
                        "title": f"Day {i + 1}",
                        "focus": "Full Body",
                        "durationMinutes": 45,
                        "exercises": [
                            {
                                "exerciseId": eid,
                                "sets": 3,
                                "reps": 10,
                                "restSeconds": 60,
                            }
                        ],
                    }
                )
            return json.dumps(
                {
                    "title": "AI Solo Week",
                    "focus": "General Fitness",
                    "durationMinutes": 45,
                    "level": "Beginner",
                    "daysPerWeek": day_count,
                    "notes": last[:200] or "Generated by mock AI",
                    "days": days,
                }
            )
        return (
            "Got it — keep training consistent this week. "
            "Hit your prescribed sets, sleep well, and message me if form feels off."
        )

    async def stream(
        self,
        messages: list[dict[str, Any]],
        *,
        temperature: float,
        max_tokens: int,
    ) -> AsyncIterator[str]:
        text = await self.complete(messages, temperature=temperature, max_tokens=max_tokens)
        size = 24
        for i in range(0, len(text), size):
            yield text[i : i + size]
